#!/usr/bin/env python3
"""Cross-Desk Fine-Tuning Script for SmartDeskPower.

Authors: Andrea Pedrini, Pietro Bellini
Platform: Arduino Nano 33 BLE Sense (Cortex-M4F @ 64 MHz)

Adapts the pre-trained model to a new desk material (e.g. glass, MDF, pine)
using a small calibration set (~5-10 windows per class, ~2 minutes total).
Freezes the feature representation layers (Dense 1 and 2) and trains only
the output classification layer, exporting the updated model.h header.
"""

import os
import argparse
import numpy as np
import pandas as pd
from sklearn.metrics import accuracy_score
import tensorflow as tf
from tensorflow.keras import layers, models

CLASSES = ["idle", "typing", "writing", "handling", "incidental"]
CLASS_TO_IDX = {name: i for i, name in enumerate(CLASSES)}
WINDOW_SAMPLES = 119
N_FEATURES = 33


def channel_stats(x):
    n = len(x)
    mean_val = np.mean(x)
    var_val = max(0.0, np.mean(x**2) - mean_val**2)
    std_val = np.sqrt(var_val)
    rms_val = np.sqrt(np.mean(x**2))
    min_val = np.min(x)
    max_val = np.max(x)
    range_val = max_val - min_val
    mean_abs = np.mean(np.abs(x))

    centered = x - mean_val
    zc = np.sum((centered[:-1] >= 0) != (centered[1:] >= 0))
    zcr = zc / n

    return [mean_val, std_val, rms_val, min_val, max_val, range_val, mean_abs, zcr]


def extract_features(window):
    ax = window[:, 0]
    ay = window[:, 1]
    az = window[:, 2]
    mag = np.sqrt(ax**2 + ay**2 + az**2)

    feats = []
    feats.extend(channel_stats(ax))
    feats.extend(channel_stats(ay))
    feats.extend(channel_stats(az))
    feats.extend(channel_stats(mag))

    sub_n = 12
    n_subs = int(np.ceil(len(mag) / sub_n))
    sub_rms = []
    for s in range(n_subs):
        start = s * sub_n
        end = min(start + sub_n, len(mag))
        sub_rms.append(np.sqrt(np.mean(mag[start:end]**2)))

    burstiness = np.std(sub_rms, ddof=0)
    feats.append(burstiness)

    return np.array(feats, dtype=np.float32)


def load_desk_dataset(dataset_dir):
    X_windows = []
    y_labels = []

    for label in CLASSES:
        csv_file = os.path.join(dataset_dir, f"{label}.csv")
        if os.path.exists(csv_file):
            df = pd.read_csv(csv_file)
            cols = [c for c in df.columns if c.strip().lower() in ['ax', 'ay', 'az']]
            data = df[cols].values

            n_samples = len(data)
            n_windows = n_samples // WINDOW_SAMPLES
            print(f"Loaded '{label}': {n_windows} calibration windows ({n_samples} samples)")

            for w in range(n_windows):
                start = w * WINDOW_SAMPLES
                end = start + WINDOW_SAMPLES
                X_windows.append(data[start:end])
                y_labels.append(CLASS_TO_IDX[label])
        else:
            print(f"Warning: Missing '{csv_file}'! Please record at least a few samples for '{label}'.")

    if len(X_windows) == 0:
        raise ValueError(f"No valid calibration data found in '{dataset_dir}'!")

    return np.array(X_windows, dtype=np.float32), np.array(y_labels, dtype=np.int32)


def export_model_h(model, norm_mean, norm_std, filepath):
    weights = model.get_weights()
    w1, b1 = weights[0], weights[1]
    w2, b2 = weights[2], weights[3]
    w3, b3 = weights[4], weights[5]

    lines = []
    lines.append("#ifndef MODEL_FINETUNED_H")
    lines.append("#define MODEL_FINETUNED_H")
    lines.append("")
    lines.append("// ── Generated by finetune.py (Cross-Desk Calibrated) ──")
    lines.append('#include "config.h"')
    lines.append("")
    lines.append("static const char* CLASS_LABELS[N_CLASSES] = {")
    labels_str = ", ".join([f'\"{name}\"' for name in CLASSES])
    lines.append(f"  {labels_str}")
    lines.append("};")
    lines.append("")

    lines.append(f"// Z-score normalization ({len(norm_mean)} features)")
    lines.append(f"static const float NORM_MEAN[N_FEATURES] = {{")
    lines.append("  " + ", ".join([f"{v:.6f}f" for v in norm_mean]))
    lines.append("};")
    lines.append(f"static const float NORM_STD[N_FEATURES] = {{")
    lines.append("  " + ", ".join([f"{v:.6f}f" for v in norm_std]))
    lines.append("};")
    lines.append("")

    lines.append(f"// Hand-coded MLP: {N_FEATURES} -> {w1.shape[1]} -> {w2.shape[1]} -> {w3.shape[1]}")
    lines.append(f"#define L1_IN  {w1.shape[0]}")
    lines.append(f"#define L1_OUT {w1.shape[1]}")
    lines.append(f"#define L2_IN  {w2.shape[0]}")
    lines.append(f"#define L2_OUT {w2.shape[1]}")
    lines.append(f"#define L3_IN  {w3.shape[0]}")
    lines.append(f"#define L3_OUT {w3.shape[1]}")
    lines.append("")

    def dump_array(name, arr):
        flat = arr.flatten()
        elems = ", ".join([f"{v:.6f}f" for v in flat])
        return f"static const float {name}[{len(flat)}] = {{\n  {elems}\n}};"

    lines.append(dump_array("MLP_W1", w1))
    lines.append(dump_array("MLP_B1", b1))
    lines.append(dump_array("MLP_W2", w2))
    lines.append(dump_array("MLP_B2", b2))
    lines.append(dump_array("MLP_W3", w3))
    lines.append(dump_array("MLP_B3", b3))
    lines.append("")
    lines.append("#endif // MODEL_FINETUNED_H")
    lines.append("")

    os.makedirs(os.path.dirname(filepath), exist_ok=True)
    with open(filepath, "w") as f:
        f.write("\n".join(lines))
    print(f"\n[OK] Successfully exported fine-tuned model to {filepath}!")


def main():
    parser = argparse.ArgumentParser(description="Cross-Desk Fine-Tuning for SmartDeskPower")
    parser.add_argument("--calib-dir", default="dataset_new_desk",
                        help="Folder containing calibration CSVs (default: dataset_new_desk)")
    parser.add_argument("--base-data", default="dataset",
                        help="Folder containing original pre-training dataset (default: dataset)")
    parser.add_argument("--out-header", default="SmartDeskPower_Pedrini_Bellini/model_finetuned.h",
                        help="Output header file path (default: model_finetuned.h)")
    parser.add_argument("--epochs", type=int, default=20)
    args = parser.parse_args()

    print("=" * 70)
    print("CROSS-DESK FINE-TUNING PIPELINE — SMART DESK POWER MANAGER")
    print("=" * 70)

    # 1. Train base model on primary dataset
    print("\n[Step 1/3] Loading pre-training reference dataset...")
    X_base, y_base = load_desk_dataset(args.base_data)
    X_base_feats = np.array([extract_features(w) for w in X_base])

    norm_mean = np.mean(X_base_feats, axis=0)
    norm_std = np.std(X_base_feats, axis=0)
    norm_std[norm_std < 1e-8] = 1.0

    X_base_norm = (X_base_feats - norm_mean) / norm_std

    print("Training base feature extractor model...")
    model = models.Sequential([
        layers.Input(shape=(N_FEATURES,)),
        layers.Dense(12, activation='relu', name='dense_1'),
        layers.Dense(6, activation='relu', name='dense_2'),
        layers.Dense(len(CLASSES), activation='softmax', name='output')
    ])
    model.compile(
        optimizer=tf.keras.optimizers.Adam(learning_rate=0.005),
        loss='sparse_categorical_crossentropy',
        metrics=['accuracy']
    )
    model.fit(X_base_norm, y_base, epochs=30, batch_size=16, verbose=0)
    base_acc = accuracy_score(y_base, np.argmax(model.predict(X_base_norm, verbose=0), axis=1))
    print(f"Base Model Pre-training Accuracy: {base_acc * 100:.1f}%")

    # 2. Load new desk calibration data
    print(f"\n[Step 2/3] Loading new desk calibration data from '{args.calib_dir}'...")
    if not os.path.exists(args.calib_dir):
        print(f"\n[!] Calibration folder '{args.calib_dir}' does not exist yet.")
        print(f"To create it, run record_serial.py saving to '{args.calib_dir}':")
        for label in CLASSES:
            print(f"   python3 record_serial.py --port <PORT> --dir {args.calib_dir} --label {label}")
        return 1

    X_new, y_new = load_desk_dataset(args.calib_dir)
    X_new_feats = np.array([extract_features(w) for w in X_new])

    # Re-normalize with local desk baseline mean and std
    norm_mean = np.mean(X_new_feats, axis=0)
    norm_std = np.std(X_new_feats, axis=0)
    norm_std[norm_std < 1e-8] = 1.0
    X_new_norm = (X_new_feats - norm_mean) / norm_std

    # 3. Freeze lower representation layers, train only output layer
    print("\n[Step 3/3] Freezing Dense_1 and Dense_2, fine-tuning output layer...")
    model.get_layer('dense_1').trainable = False
    model.get_layer('dense_2').trainable = False

    model.compile(
        optimizer=tf.keras.optimizers.Adam(learning_rate=0.002),
        loss='sparse_categorical_crossentropy',
        metrics=['accuracy']
    )

    model.fit(X_new_norm, y_new, epochs=args.epochs, batch_size=8, verbose=1)

    ft_preds = np.argmax(model.predict(X_new_norm, verbose=0), axis=1)
    ft_acc = accuracy_score(y_new, ft_preds)
    print(f"\n[Result] Fine-Tuned Accuracy on New Desk: {ft_acc * 100:.1f}%")

    # Export header
    export_model_h(model, norm_mean, norm_std, args.out_header)
    print("\nNext step: Upload SmartDeskPower_Pedrini_Bellini.ino to Arduino via Arduino IDE.")
    return 0


if __name__ == "__main__":
    main()
